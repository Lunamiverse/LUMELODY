#!/usr/bin/env python3
"""Generate the plugin's embedded files from the same sources as the web instrument.

  plugin/ui/index.html        the approved interface (web/instrument_template.html) with the fonts served locally
  plugin/Source/PresetData.h  every sound's flattened engine parameters, so the plugin can load them natively

Run after changing presets or the interface:  python3 plugin/build_ui.py   (needs build/schema_dump)
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "web"))
from build_page import preset_data, schema_json, template  # noqa: E402

data = preset_data()
schema = schema_json()

html = template()
links = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
         '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Pixelify+Sans:wght@400..700&family=Silkscreen&display=swap">')
assert links in html, "font links changed in the template"
faces = ('<style>\n'
         '@font-face { font-family: "Pixelify Sans"; src: url("fonts/PixelifySans.ttf") format("truetype"); font-weight: 400 700; font-display: block; }\n'
         '@font-face { font-family: "Silkscreen"; src: url("fonts/Silkscreen-Regular.ttf") format("truetype"); font-weight: 400; font-display: block; }\n'
         '</style>')
html = html.replace(links, faces).replace("__PRESETS__", json.dumps(data)).replace("__SCHEMA__", schema)
html = '<!doctype html>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n' + html
os.makedirs(os.path.join(HERE, "ui"), exist_ok=True)
open(os.path.join(HERE, "ui", "index.html"), "w").write(html)

def lit(s):
    assert ")LUMI\"" not in s
    return 'R"LUMI(' + s + ')LUMI"'

rows = []
for d in data:
    rows.append("    { %s, %s, %s, %d, %s }," % (json.dumps(d["id"]), json.dumps(d["name"]), json.dumps(d["cat"]), d["baseNote"], lit(d["params"])))
hdr = """// Generated by plugin/build_ui.py from tools/previews/preset_defs.py -- do not edit by hand.
#pragma once

namespace lumi {
struct PresetEntry { const char* id; const char* name; const char* category; int baseNote; const char* params; };
static const PresetEntry kPresets[] = {
%s
};
static constexpr int kNumPresets = (int) (sizeof (kPresets) / sizeof (kPresets[0]));
}  // namespace lumi
""" % "\n".join(rows)
open(os.path.join(HERE, "Source", "PresetData.h"), "w").write(hdr)
print(len(data), "presets,", len(html), "bytes of UI")
